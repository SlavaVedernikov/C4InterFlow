using System.CommandLine;
using System.CommandLine.Parsing;
using C4InterFlow.Cli.Commands;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace C4InterFlow.Cli.Configuration;

/// <summary>
/// Builds the JSON schema of the 'commands' section of the configuration file from the CLI commands themselves,
/// so the options of a command are defined in one place only.
/// </summary>
public static class CommandsSchemaBuilder
{
    public const string FILE_NAME = "commands-schema.json";

    private const string OUTPUT_DIR_OPTION = "output-dir";

    // Commands that are not meant to be used in the configuration file.
    private static readonly HashSet<string> ExcludedCommands = new()
    {
        ExecuteCommandsCommand.COMMAND_NAME,
        ExportSchemaCommand.COMMAND_NAME
    };

    /// <summary>
    /// The commands that can be used in the configuration file.
    /// </summary>
    public static IReadOnlyList<Command> GetSupportedCommands(Parser parser)
    {
        return parser.Configuration.RootCommand.Subcommands
            .Where(x => !ExcludedCommands.Contains(x.Name))
            .ToList();
    }

    /// <summary>
    /// The name of an option in the configuration file, e.g. aac-input-paths becomes aacInputPaths.
    /// </summary>
    public static string ToKey(string optionName)
    {
        var segments = optionName.Split('-', StringSplitOptions.RemoveEmptyEntries);

        return segments[0] + string.Concat(segments.Skip(1).Select(x => char.ToUpperInvariant(x[0]) + x[1..]));
    }

    /// <summary>
    /// Builds the schema. The result is deterministic, so it can be compared with a committed copy.
    /// </summary>
    public static JObject Build(Parser parser)
    {
        var commands = GetSupportedCommands(parser);

        var definitions = new JObject
        {
            ["CommandEntry"] = BuildCommandEntry(parser, commands)
        };

        foreach (var command in commands)
        {
            definitions[GetOptionsDefinitionName(command)] = BuildOptions(parser, command);
        }

        return new JObject
        {
            ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
            ["title"] = "C4InterFlow commands",
            ["description"] = "The commands that can be executed with 'execute-commands'. This file is generated by the 'export-schema' command. Do not edit it.",
            ["type"] = "array",
            ["items"] = new JObject { ["$ref"] = "#/$defs/CommandEntry" },
            ["minItems"] = 1,
            ["$defs"] = definitions
        };
    }

    /// <summary>
    /// Builds the schema and formats it the same way on every platform.
    /// </summary>
    public static string BuildText(Parser parser)
    {
        using var writer = new StringWriter { NewLine = "\n" };
        using (var jsonWriter = new JsonTextWriter(writer) { Formatting = Formatting.Indented, Indentation = 2 })
        {
            Build(parser).WriteTo(jsonWriter);
        }

        return writer.ToString() + "\n";
    }

    private static JObject BuildCommandEntry(Parser parser, IReadOnlyList<Command> commands)
    {
        var rules = new JArray();

        foreach (var command in commands)
        {
            var hasRequiredOptions = GetOptionInfos(parser, command).Any(x => x.IsRequired);
            var hasOutputDir = command.Options.Any(x => x.Name == OUTPUT_DIR_OPTION);

            var then = new JObject
            {
                ["properties"] = new JObject
                {
                    ["options"] = new JObject { ["$ref"] = $"#/$defs/{GetOptionsDefinitionName(command)}" }
                }
            };

            if (hasRequiredOptions)
            {
                then["required"] = new JArray("options");
            }

            if (hasOutputDir)
            {
                // Clearing the output directory needs to know which directory that is.
                then["if"] = new JObject
                {
                    ["properties"] = new JObject { ["clearOutputDir"] = new JObject { ["const"] = true } },
                    ["required"] = new JArray("clearOutputDir")
                };
                then["then"] = new JObject
                {
                    ["required"] = new JArray("options"),
                    ["properties"] = new JObject
                    {
                        ["options"] = new JObject { ["required"] = new JArray(ToKey(OUTPUT_DIR_OPTION)) }
                    }
                };
            }
            else
            {
                ((JObject)then["properties"]!)["clearOutputDir"] = new JObject
                {
                    ["const"] = false,
                    ["description"] = $"'clearOutputDir' is not supported by '{command.Name}', as it has no '--{OUTPUT_DIR_OPTION}' option."
                };
            }

            rules.Add(new JObject
            {
                ["if"] = new JObject
                {
                    ["properties"] = new JObject { ["command"] = new JObject { ["const"] = command.Name } },
                    ["required"] = new JArray("command")
                },
                ["then"] = then
            });
        }

        return new JObject
        {
            ["description"] = "A command to execute.",
            ["type"] = "object",
            ["properties"] = new JObject
            {
                ["command"] = new JObject
                {
                    ["description"] = "The name of the command to execute.",
                    ["enum"] = new JArray(commands.Select(x => x.Name))
                },
                ["clearOutputDir"] = new JObject
                {
                    ["description"] = $"If true, the contents of the directory specified by 'options.{ToKey(OUTPUT_DIR_OPTION)}' are deleted before the command runs. Requires '{ToKey(OUTPUT_DIR_OPTION)}'. Defaults to false.",
                    ["type"] = "boolean",
                    ["default"] = false
                },
                ["options"] = new JObject
                {
                    ["description"] = "Command-specific options. The allowed options depend on the value of 'command'.",
                    ["type"] = "object"
                }
            },
            ["required"] = new JArray("command"),
            ["additionalProperties"] = false,
            ["allOf"] = rules
        };
    }

    private static JObject BuildOptions(Parser parser, Command command)
    {
        var properties = new JObject();
        var required = new JArray();

        foreach (var info in GetOptionInfos(parser, command))
        {
            var key = ToKey(info.Option.Name);

            properties[key] = BuildOption(info);

            if (info.IsRequired)
            {
                required.Add(key);
            }
        }

        var result = new JObject
        {
            ["description"] = $"Options of the '{command.Name}' command. {command.Description}".Trim(),
            ["type"] = "object",
            ["properties"] = properties
        };

        if (required.Count > 0)
        {
            result["required"] = required;
        }

        result["additionalProperties"] = false;

        return result;
    }

    private static JObject BuildOption(OptionInfo info)
    {
        var (option, defaultValue, isRequired) = (info.Option, info.Default, info.IsRequired);

        var valueType = Nullable.GetUnderlyingType(option.ValueType) ?? option.ValueType;
        var isList = valueType.IsArray;
        var itemType = isList ? valueType.GetElementType()! : valueType;

        var result = new JObject();

        if (!string.IsNullOrWhiteSpace(option.Description))
        {
            result["description"] = option.Description;
        }

        var item = BuildValueSchema(option, itemType);

        if (isList)
        {
            result["type"] = "array";
            result["items"] = item;

            if (isRequired)
            {
                result["minItems"] = 1;
            }
        }
        else
        {
            foreach (var property in item.Properties())
            {
                result[property.Name] = property.Value;
            }
        }

        if (HasDefault(defaultValue) && !IsCurrentDirectory(defaultValue))
        {
            // The current directory is different on every machine and must not end up in the schema.
            result["default"] = JToken.FromObject(defaultValue!);
        }

        return result;
    }

    private static JObject BuildValueSchema(Option option, Type type)
    {
        if (type == typeof(bool))
        {
            return new JObject { ["type"] = "boolean" };
        }

        if (type == typeof(int) || type == typeof(long))
        {
            return new JObject { ["type"] = "integer" };
        }

        var result = new JObject { ["type"] = "string" };

        var allowedValues = option.GetCompletions().Select(x => x.Label).ToList();
        if (allowedValues.Count > 0)
        {
            result.Remove("type");
            result["enum"] = new JArray(allowedValues);
        }

        return result;
    }

    private sealed record OptionInfo(Option Option, object? Default, bool IsRequired);

    // The default of an option can only be read by parsing the command without any arguments.
    // An option has to be specified in the configuration file if the command requires it and does not default it.
    private static IReadOnlyList<OptionInfo> GetOptionInfos(Parser parser, Command command)
    {
        var defaults = parser.Parse(new[] { command.Name });

        return command.Options
            .Select(option =>
            {
                var defaultValue = defaults.GetValueForOption(option);

                return new OptionInfo(option, defaultValue, option.IsRequired && !HasDefault(defaultValue));
            })
            .ToList();
    }

    private static bool HasDefault(object? value)
    {
        return value switch
        {
            null => false,
            string text => text.Length > 0,
            Array array => array.Length > 0,
            _ => true
        };
    }

    private static bool IsCurrentDirectory(object? value)
    {
        return value is string text && string.Equals(text, Directory.GetCurrentDirectory(), StringComparison.OrdinalIgnoreCase);
    }

    private static string GetOptionsDefinitionName(Command command)
    {
        return string.Concat(command.Name.Split('-', StringSplitOptions.RemoveEmptyEntries)
            .Select(x => char.ToUpperInvariant(x[0]) + x[1..])) + "Options";
    }
}
